#!/usr/bin/env python3
"""Offline binary64 constants for private SF003-PERF candidates; no runtime init."""
import argparse
import hashlib
from decimal import Decimal, localcontext
from pathlib import Path

TARGET=Path(__file__).resolve().parents[1]/'src/germanium_exp_tables.h'


def generate():
    with localcontext() as ctx:
        ctx.prec=90
        half=Decimal.from_float(float(Decimal(2).ln()/2))
        out=['#pragma once','// Generated by tools/generate_germanium_exp.py (Decimal90); do not edit.',
             '#include <array>','namespace parable::dsp::germanium_detail::tables {',
             'struct Cubic {double a0,a1,a2,a3;};']
        for cells in (32,64):
            h=half/cells
            out.append(f'inline constexpr double step{cells}={float(h).hex()};')
            for sign,label in ((1,''),(-1,'negative')):
                out.append(f'inline constexpr std::array<Cubic,{cells}> hermite{cells}{label}{{{{')
                step=sign*h
                for i in range(cells):
                    x=step*i;e0=x.exp();e1=(x+step).exp();y0=e0-1;y1=e1-1
                    c2=(3*(y1-y0)-step*(2*e0+e1))/(step*step)
                    c3=(step*(e0+e1)-2*(y1-y0))/(step*step*step)
                    values=[float(v) for v in (y0,e0,c2,c3)]
                    if sign<0 and i==0:values[0]=-0.0
                    out.append('    {'+','.join(v.hex() for v in values)+'},')
                out.append('}};')
        for degree in (8,12):
            coeff=[Decimal(0),Decimal(1)];factorial=1
            for i in range(2,degree+1):
                factorial*=i;coeff.append(Decimal(1)/factorial)
            powers=list(range(degree-3,degree+1));matrix=[]
            for x in (-half,half):
                value=sum(c*x**i for i,c in enumerate(coeff))
                derivative=sum(i*c*x**(i-1) for i,c in enumerate(coeff) if i)
                matrix.append([x**i for i in powers]+[(x.exp()-1)-value])
                matrix.append([i*x**(i-1) for i in powers]+[x.exp()-derivative])
            for col in range(4):
                pivot=matrix[col][col]
                matrix[col]=[v/pivot for v in matrix[col]]
                for row in range(4):
                    if row!=col:
                        scale=matrix[row][col]
                        matrix[row]=[a-scale*b for a,b in zip(matrix[row],matrix[col])]
            for i,row in zip(powers,matrix):coeff[i]+=row[-1]
            out.append(f'inline constexpr std::array<double,{degree+1}> poly{degree}{{{{'+','.join(float(c).hex() for c in coeff)+'}};')
        out.append('} // namespace parable::dsp::germanium_detail::tables')
    return '\n'.join(out)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text()!=text:raise SystemExit('Germanium exponential constants differ from generator')
    else:TARGET.write_text(text)
    print('Germanium constants SHA256',hashlib.sha256(text.encode()).hexdigest())
