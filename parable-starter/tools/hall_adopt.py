#!/usr/bin/env python3
"""Reproduce native kCathedral extraction; no algorithm regenerated or replaced."""
from pathlib import Path
import argparse,hashlib,json
root=Path(__file__).resolve().parents[1];src=root/'third_party/hall/upstream'
pins=json.loads((src.parent/'provenance.json').read_text())
for name,digest in pins['source_sha256'].items():
 assert hashlib.sha256((src/name).read_bytes()).hexdigest()==digest, name
h=(src/'kCathedral.h').read_text();cpp=(src/'kCathedral.cpp').read_text();proc=(src/'kCathedralProc.cpp').read_text()
constants=h[h.index('//regular3x3'):h.index('const int kNumPrograms')]
state=h[h.index('\tdouble gainOutL;'):h.index('\n};',h.index('\tdouble gainOutL;'))]
ctor=cpp[cpp.index('\tA = 1.0;'):cpp.index('    _canDo.insert(')]
ctor=ctor.replace('fpdL = 1.0; while (fpdL < 16386) fpdL = rand()*UINT32_MAX;','fpdL = 3249348619u;').replace('fpdR = 1.0; while (fpdR < 16386) fpdR = rand()*UINT32_MAX;','fpdR = 2430999997u;')
body=proc[proc.index('void kCathedral::processReplacing'):proc.index('void kCathedral::processDoubleReplacing')]
body=body.replace('void kCathedral::processReplacing(float **inputs, float **outputs, VstInt32 sampleFrames)','void Core::process(float **inputs, float **outputs, int32_t sampleFrames) noexcept')
body=body.replace('0.000293','regeneration')
# Change only the final existing scattering plane, complete five-path vectors.
import re
pattern=r'(\s*)(feedback\w+) = (\(\(out(\w+)\*3\.0\) - \(\(.+?\)\*2\.0\)\));'
def focus(m):return f'{m[1]}{m[2]} = scatter({m[3]}, out{m[4]}*5.0);'
body,n=re.subn(pattern,focus,body);assert n==10,n
header='''// Derived from Airwindows kCathedral; MIT, Chris Johnson. See upstream/LICENSE.
// Generated by tools/hall_adopt.py. No VST/SDK dependency in native DSP.
#pragma once
#include <cstdint>
namespace parable::hall_detail {
'''+constants+'''class Core {
public:
    Core() noexcept { reset(); }
    void reset() noexcept;
    void process(float**,float**,int32_t) noexcept;
    double rate=48000, regeneration=0.000293, focusing=0;
private:
    double getSampleRate() const noexcept { return rate; }
    double scatter(double diffuse, double coherent) const noexcept {
        return focusing==0 ? diffuse : diffuse + focusing*(coherent-diffuse);
    }
'''+state+'\n};\n}\n'
# Member zeroing is safe here: a trivially-copyable, nonpolymorphic scalar/array
# state with IEEE float representations and no pointers/resources. Controls survive.
source='''// Derived from Airwindows kCathedral; MIT. See third_party/hall/upstream/LICENSE.
// Generated by tools/hall_adopt.py; retained original complete float-I/O DSP.
#include "hall_core.h"
#include <cmath>
#include <cstring>
#include <type_traits>
namespace parable::hall_detail {
static_assert(std::is_trivially_copyable_v<Core>);
void Core::reset() noexcept {
    const double oldRate=rate, oldRegen=regeneration, oldFocus=focusing;
    std::memset(static_cast<void*>(this),0,sizeof(*this));
    rate=oldRate; regeneration=oldRegen; focusing=oldFocus;
'''+ctor+'\n}\n'+body+'\n}\n'
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
for p,text in [(root/'src/hall_core.h',header),(root/'src/hall_core.cpp',source)]:
 if args.check:
  assert p.read_text()==text, f'{p} differs from reproducible adapter'
 else:p.write_text(text)
